-- Flyo Disruption Recovery Platform: Production Schema Migration V1
-- Target Database: PostgreSQL 14+ (ANSI SQL standard compatible with H2)

-- 1. Monitored Passenger Bookings
CREATE TABLE IF NOT EXISTS bookings (
    id VARCHAR(36) PRIMARY KEY,
    passenger_name VARCHAR(128) NOT NULL,
    pnr VARCHAR(32) NOT NULL,
    route VARCHAR(64) NOT NULL,
    flight VARCHAR(32) NOT NULL,
    date_time VARCHAR(64) NOT NULL,
    onward_flight VARCHAR(128) DEFAULT 'None',
    hotel_note VARCHAR(128) DEFAULT 'None',
    agency VARCHAR(64) NOT NULL DEFAULT 'Flyo',
    status VARCHAR(32) NOT NULL DEFAULT 'Checked-in'
);

CREATE INDEX IF NOT EXISTS idx_bookings_pnr ON bookings(pnr);
CREATE INDEX IF NOT EXISTS idx_bookings_flight ON bookings(flight);

-- 2. Disruption Recovery Cases
CREATE TABLE IF NOT EXISTS rescue_cases (
    id VARCHAR(36) PRIMARY KEY,
    booking_id VARCHAR(36) NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    passenger_name VARCHAR(128) NOT NULL,
    state VARCHAR(64) NOT NULL,
    cancelled_segment VARCHAR(2000),
    flight VARCHAR(32),
    impact VARCHAR(2000),
    missed_connection VARCHAR(128),
    hotel_risk VARCHAR(128),
    approved_option_id VARCHAR(36),
    approved_by VARCHAR(64),
    approved_at TIMESTAMP,
    new_pnr VARCHAR(32),
    error VARCHAR(2000),
    manual_next_step VARCHAR(2000),
    version BIGINT DEFAULT 0,
    created_at TIMESTAMP,
    updated_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_rescue_cases_booking_id ON rescue_cases(booking_id);
CREATE INDEX IF NOT EXISTS idx_rescue_cases_state ON rescue_cases(state);

-- 3. Ranked Recovery Options
CREATE TABLE IF NOT EXISTS rebook_options (
    id VARCHAR(36) PRIMARY KEY,
    case_id VARCHAR(36) NOT NULL,
    flight VARCHAR(32) NOT NULL,
    route VARCHAR(128) NOT NULL,
    departure VARCHAR(64) NOT NULL,
    arrival VARCHAR(64) NOT NULL,
    connection_minutes INT NOT NULL,
    extra_cost INT NOT NULL DEFAULT 0,
    rank INT NOT NULL,
    saves_connection BOOLEAN NOT NULL DEFAULT FALSE,
    reason TEXT
);

CREATE INDEX IF NOT EXISTS idx_rebook_options_case_rank ON rebook_options(case_id, rank);

-- 4. Immutable Append-Only Audit Trail
CREATE TABLE IF NOT EXISTS audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id VARCHAR(36) NOT NULL,
    timestamp TIMESTAMP NOT NULL,
    event VARCHAR(64) NOT NULL,
    actor VARCHAR(64) NOT NULL,
    detail VARCHAR(2000)
);

CREATE INDEX IF NOT EXISTS idx_audit_events_case_time ON audit_events(case_id, timestamp);

-- 5. Treasury Virtual Commercial Cards
CREATE TABLE IF NOT EXISTS virtual_cards (
    id VARCHAR(36) PRIMARY KEY,
    case_id VARCHAR(36) NOT NULL,
    option_id VARCHAR(36) NOT NULL,
    card_number VARCHAR(32) NOT NULL,
    card_holder VARCHAR(128),
    expiry VARCHAR(16) NOT NULL,
    cvv VARCHAR(32) NOT NULL,
    amount INT NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'INR',
    status VARCHAR(32) NOT NULL DEFAULT 'ISSUED',
    merchant_category VARCHAR(64) DEFAULT '3000 - Airlines',
    issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_virtual_cards_case ON virtual_cards(case_id);

-- 6. Settlement Transaction Ledger
CREATE TABLE IF NOT EXISTS payment_transactions (
    id VARCHAR(36) PRIMARY KEY,
    case_id VARCHAR(36) NOT NULL,
    virtual_card_id VARCHAR(36) NOT NULL,
    amount INT NOT NULL,
    currency VARCHAR(8) NOT NULL DEFAULT 'INR',
    vendor VARCHAR(128),
    status VARCHAR(32) NOT NULL DEFAULT 'SETTLED',
    reference_id VARCHAR(64) NOT NULL,
    timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_payment_transactions_case ON payment_transactions(case_id);

-- 7. WhatsApp / Customer Communication Ledger
CREATE TABLE IF NOT EXISTS simulated_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id VARCHAR(36) NOT NULL,
    type VARCHAR(64) NOT NULL,
    recipient VARCHAR(128) NOT NULL,
    text VARCHAR(2000) NOT NULL,
    timestamp TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_messages_case ON simulated_messages(case_id);

-- 8. Formal State Lifecycle Transitions Ledger
CREATE TABLE IF NOT EXISTS state_transitions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id VARCHAR(36) NOT NULL,
    from_state VARCHAR(64),
    to_state VARCHAR(64) NOT NULL,
    actor VARCHAR(64) NOT NULL,
    reason TEXT,
    timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_state_transitions_case ON state_transitions(case_id, timestamp);

-- 9. Durable Transactional Outbox Pattern
CREATE TABLE IF NOT EXISTS outbox_events (
    id VARCHAR(36) PRIMARY KEY,
    aggregate_type VARCHAR(64) NOT NULL,
    aggregate_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(64) NOT NULL,
    payload TEXT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    retry_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    processed_at TIMESTAMP,
    error_message TEXT
);

CREATE INDEX IF NOT EXISTS idx_outbox_status_created ON outbox_events(status, created_at);

-- 10. Operator & System User Accounts (RBAC)
CREATE TABLE IF NOT EXISTS operator_accounts (
    id VARCHAR(36) PRIMARY KEY,
    username VARCHAR(64) UNIQUE NOT NULL,
    password_hash VARCHAR(128) NOT NULL,
    full_name VARCHAR(128) NOT NULL,
    role VARCHAR(32) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    phone_number VARCHAR(32)
);

CREATE INDEX IF NOT EXISTS idx_operator_username ON operator_accounts(username);
